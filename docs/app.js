  function bestValues() {
    var best = {};
    SUMMARY_COLUMNS.forEach(function (col) {
      if (!col.better) return;
      var values = state.selected.map(function (name) {
        var run = state.runs[name];
        return col.key === 'dispatches' ? run.dispatches : run.summary[col.key];
      }).filter(function (v) { return isFinite(v); });
      if (values.length === 0) return;
      best[col.key] = col.better === 'lower' ? Math.min.apply(null, values) : Math.max.apply(null, values);
    });
    return best;
  }

  function renderSummary() {
    var best = bestValues();
    var html = '';
    state.selected.forEach(function (name) {
      var run = state.runs[name];
      html += '<tr' + (name === state.active ? ' class="is-active"' : '') + '>' +
        '<td><span class="card-swatch" style="background:' + SCHEDULER_COLORS[name] + '"></span>' +
        esc(MFTS.SCHEDULER_LABEL[name] || name) + '</td>';
      SUMMARY_COLUMNS.forEach(function (col) {
        var raw = col.key === 'dispatches' ? run.dispatches : run.summary[col.key];
        var cls = 'num';
        if (col.better && isFinite(raw) && isFinite(best[col.key]) && Math.abs(raw - best[col.key]) < 1e-12) {
          cls += ' best';
        }
        html += '<td class="' + cls + '">' + (col.digits === 0 ? raw : fmt(raw, col.digits)) + '</td>';
      });
      html += '</tr>';
    });
    el.summaryBody.innerHTML = html;
  }

  function drawBarChart(canvas, values, labels, colors, digits) {
    var dpr = window.devicePixelRatio || 1;
    var cssWidth = canvas.parentElement.clientWidth - 24;
    var cssHeight = 200;
    canvas.width = Math.max(200, Math.round(cssWidth * dpr));
    canvas.height = Math.round(cssHeight * dpr);
    canvas.style.height = cssHeight + 'px';
    var ctx = canvas.getContext('2d');
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, cssWidth, cssHeight);

    var padLeft = 96;
    var padRight = 56;
    var padTop = 8;
    var rowHeight = (cssHeight - padTop * 2) / Math.max(1, values.length);
    var barHeight = Math.min(22, rowHeight * 0.62);
    var max = Math.max.apply(null, values.concat([0]));
    var plotWidth = Math.max(40, cssWidth - padLeft - padRight);

    ctx.font = '12px -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif';
    ctx.textBaseline = 'middle';

    values.forEach(function (value, i) {
      var y = padTop + rowHeight * i + rowHeight / 2;
      var w = max > 0 ? (value / max) * plotWidth : 0;
      ctx.fillStyle = '#8d9aa8';
      ctx.textAlign = 'right';
      ctx.fillText(labels[i], padLeft - 10, y);
      ctx.fillStyle = colors[i];
      ctx.fillRect(padLeft, y - barHeight / 2, Math.max(1, w), barHeight);
      ctx.fillStyle = '#e6edf3';
      ctx.textAlign = 'left';
      ctx.fillText(fmt(value, digits), padLeft + Math.max(1, w) + 8, y);
    });
  }

