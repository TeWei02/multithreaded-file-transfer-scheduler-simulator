  function niceTickStep(span) {
    var raw = span / 8;
    var pow = Math.pow(10, Math.floor(Math.log(raw) / Math.LN10));
    var candidates = [1, 2, 2.5, 5, 10];
    for (var i = 0; i < candidates.length; i++) {
      if (raw <= candidates[i] * pow) return candidates[i] * pow;
    }
    return 10 * pow;
  }

  function renderGantt() {
    var canvas = el.gantt;
    var run = state.runs[state.active];
    if (!run) return;
    var threads = state.config.threads;
    var dpr = window.devicePixelRatio || 1;
    var cssWidth = canvas.parentElement.clientWidth - 20;
    var gutter = 62;
    var axisHeight = 34;
    var rowHeight = Math.max(13, Math.min(30, 210 / threads));
    var cssHeight = Math.max(120, axisHeight + rowHeight * threads + 12);
    canvas.width = Math.max(320, Math.round(cssWidth * dpr));
    canvas.height = Math.round(cssHeight * dpr);
    canvas.style.height = cssHeight + 'px';

    var ctx = canvas.getContext('2d');
    ctx.setTransform(dpr, 0, 0, dpr, 0, 0);
    ctx.clearRect(0, 0, cssWidth, cssHeight);

    var makespan = Math.max(state.makespan, 1e-6);
    var plotWidth = Math.max(60, cssWidth - gutter - 12);
    function xOf(t) { return gutter + (t / makespan) * plotWidth; }

    ctx.font = '11px ui-monospace, SFMono-Regular, Menlo, monospace';
    ctx.textBaseline = 'middle';

    // time axis
    var step = niceTickStep(makespan);
    ctx.strokeStyle = '#1e2733';
    ctx.fillStyle = '#8d9aa8';
    ctx.textAlign = 'center';
    for (var t = 0; t <= makespan + 1e-9; t += step) {
      var x = xOf(t);
      ctx.beginPath();
      ctx.moveTo(x, axisHeight - 8);
      ctx.lineTo(x, cssHeight - 6);
      ctx.stroke();
      ctx.fillText(t.toFixed(t < 1 ? 2 : (step < 1 ? 1 : 0)) + 's', x, axisHeight - 18);
    }

    // arrival markers
    var seenArrival = {};
    state.requests.forEach(function (req) {
      var key = req.requestId;
      if (seenArrival[key]) return;
      seenArrival[key] = true;
      var x = xOf(Math.min(req.arrivalTime, makespan));
      ctx.fillStyle = clientColor(req.clientId);
      ctx.globalAlpha = 0.75;
      ctx.fillRect(x - 0.5, axisHeight - 6, 1, 5);
      ctx.globalAlpha = 1;
    });

    // worker rows
    var layout = [];
    if (threads > 26) rowHeight = Math.max(8, 210 / threads);
    for (var w = 0; w < threads; w++) {
      var y = axisHeight + w * rowHeight;
      ctx.strokeStyle = '#18202b';
      ctx.beginPath();
      ctx.moveTo(gutter, y + rowHeight - 0.5);
      ctx.lineTo(cssWidth - 6, y + rowHeight - 0.5);
      ctx.stroke();
      ctx.fillStyle = '#8d9aa8';
      ctx.textAlign = 'right';
      ctx.fillText('T' + w, gutter - 8, y + rowHeight / 2);
    }

    // slices: ghost for the not-yet-reached part, solid up to the playhead
    var revealedUpTo = state.playhead;
    run.dispatchLog.forEach(function (d) {
      var y = axisHeight + d.workerId * rowHeight + 1.5;
      var h = Math.max(3, rowHeight - 3);
      var x0 = xOf(d.start);
      var x1 = xOf(Math.min(d.finish, makespan));
      var color = clientColor(d.clientId);
      ctx.globalAlpha = 0.16;
      ctx.fillStyle = color;
      ctx.fillRect(x0, y, Math.max(1, x1 - x0), h);
      ctx.globalAlpha = 1;
      var rx1 = xOf(Math.min(d.finish, revealedUpTo));
      if (rx1 > x0) {
        ctx.fillStyle = color;
        ctx.fillRect(x0, y, Math.max(1, rx1 - x0), h);
      }
      layout.push({ x: x0, y: y, w: Math.max(1, x1 - x0), h: h, d: d });
    });

    // playhead
    var px = xOf(Math.min(revealedUpTo, makespan));
    ctx.strokeStyle = '#ff8ac2';
    ctx.lineWidth = 1.5;
    ctx.beginPath();
    ctx.moveTo(px, axisHeight - 8);
    ctx.lineTo(px, cssHeight - 6);
    ctx.stroke();
    ctx.lineWidth = 1;

    state.ganttLayout = { tiles: layout, gutter: gutter, plotWidth: plotWidth, makespan: makespan, axisHeight: axisHeight, rowHeight: rowHeight };
    renderLegend();
  }

  function renderLegend() {
    if (!state.ganttLayout) return;
    var seen = {};
    state.requests.forEach(function (r) { seen[r.clientId] = true; });
    var ids = Object.keys(seen).sort(function (a, b) { return Number(a) - Number(b); });
    el.legend.innerHTML = ids.map(function (id) {
      return '<span><span class="card-swatch" style="background:' + clientColor(id) + '"></span>client ' + esc(id) + '</span>';
    }).join('') + '<span><span class="card-swatch" style="background:#5b6572"></span>faint = beyond the playhead</span>';
  }

  function findTile(mx, my) {
    var layout = state.ganttLayout;
    if (!layout) return null;
    for (var i = 0; i < layout.tiles.length; i++) {
      var t = layout.tiles[i];
      if (mx >= t.x && mx <= t.x + t.w && my >= t.y && my <= t.y + t.h) return t.d;
    }
    return null;
  }

  function updateClock() {
    el.clock.textContent = 't = ' + fmt(state.playhead, 3) + ' s';
  }

  /* ------------------------------------------------------------------ *
   * Playback
   * ------------------------------------------------------------------ */
  function playPause() {
    if (state.playing) { stopPlayback(); return; }
    if (state.playhead >= state.makespan - 1e-9) state.playhead = 0;
    state.playing = true;
    el.playBtn.textContent = 'Pause';
    state.lastTickAt = window.performance.now();
    startLoop();
  }

  /* Animation runs on requestAnimationFrame, with a timer that steps the clock
     when frames are starved (hidden tab, no compositor). */
  function startLoop() {
    state.rafPending = true;
    state.rafId = window.requestAnimationFrame(tickFrame);
    state.watchdogId = window.setInterval(function () {
      if (!state.playing) return;
      if (window.performance.now() - state.lastTickAt > 250) tickFrame();
    }, 200);
  }

  function tickFrame() {
    state.rafPending = false;
    if (!state.playing) return;
    advanceTo(window.performance.now());
    if (state.playing) {
      state.rafPending = true;
      state.rafId = window.requestAnimationFrame(tickFrame);
    }
  }

  function advanceTo(now) {
    var dtReal = Math.min(0.1, Math.max(0, (now - state.lastTickAt) / 1000));
    state.lastTickAt = now;
    var speed = parseFloat(el.speed.value) || 1;
    var simPerSecond = state.makespan / (10 / speed);
    state.playhead = Math.min(state.makespan, state.playhead + simPerSecond * (dtReal || 0.016));
    el.scrub.value = state.makespan > 0 ? String(state.playhead / state.makespan) : '1';
    updateClock();
    renderGantt();
    if (state.playhead >= state.makespan - 1e-9) stopPlayback();
  }

  function stopPlayback() {
    state.playing = false;
    el.playBtn.textContent = 'Play';
    if (state.rafId) window.cancelAnimationFrame(state.rafId);
    if (state.watchdogId) window.clearInterval(state.watchdogId);
    state.rafId = 0;
    state.watchdogId = 0;
    state.rafPending = false;
  }

  function jumpEvent(direction) {
    var times = state.eventTimes;
    if (!times || times.length === 0) return;
    stopPlayback();
    var current = state.playhead;
    var target = direction > 0 ? state.makespan : 0;
    if (direction > 0) {
      for (var i = 0; i < times.length; i++) {
        if (times[i] > current + 1e-9) { target = times[i]; break; }
      }
    } else {
      for (var j = times.length - 1; j >= 0; j--) {
        if (times[j] < current - 1e-9) { target = times[j]; break; }
      }
    }
    state.playhead = Math.max(0, Math.min(state.makespan, target));
    el.scrub.value = state.makespan > 0 ? String(state.playhead / state.makespan) : '1';
    updateClock();
    renderGantt();
  }

  /* ------------------------------------------------------------------ *
   * Detail, client and worker tables
   * ------------------------------------------------------------------ */
  function renderDetail() {
    var run = state.runs[state.active];
    if (!run) return;
    var label = MFTS.SCHEDULER_LABEL[state.active] || state.active;
    el.detailSchedulerLabel.textContent = '· ' + label;
    el.detailSub.textContent = 'Columns match the CSV written by the command-line version (' +
      label + ', ' + state.config.threads + ' threads, quantum ' + fmt(state.config.quantumSec, 2) +
      ' s, overhead ' + fmt(state.config.overheadSec, 3) + ' s).';

    var rows = run.rows.slice().sort(function (a, b) { return a.requestId - b.requestId; });
    var html = '';
    rows.forEach(function (r) {
      html += '<tr>' +
        '<td class="num">' + r.requestId + '</td>' +
        '<td class="num">' + esc(r.clientId) + '</td>' +
        '<td class="num">' + fmt(r.arrivalTime, 2) + '</td>' +
        '<td class="num">' + fmt(r.startTime, 2) + '</td>' +
        '<td class="num">' + fmt(r.finishTime, 2) + '</td>' +
        '<td class="num">' + fmt(r.waitingTime, 2) + '</td>' +
        '<td class="num">' + fmt(r.turnaroundTime, 2) + '</td>' +
        '<td class="num">' + fmt(r.responseTime, 2) + '</td>' +
        '<td class="num">' + r.assignedThread + '</td>' +
        '</tr>';
    });
    el.detailBody.innerHTML = html;
  }

  function renderClients() {
    var run = state.runs[state.active];
    if (!run) return;
    var clients = {};
    run.requests.forEach(function (req) {
      if (req.finishTime < 0) return;
      var c = clients[req.clientId];
      if (!c) c = clients[req.clientId] = { count: 0, size: 0, first: Infinity, last: -Infinity };
      c.count += 1;
      c.size += req.fileSizeMb;
      c.first = Math.min(c.first, req.arrivalTime);
      c.last = Math.max(c.last, req.finishTime);
    });
    var html = '';
    Object.keys(clients).sort(function (a, b) { return Number(a) - Number(b); }).forEach(function (id) {
      var c = clients[id];
      var span = Math.max(1e-6, c.last - c.first);
      html += '<tr>' +
        '<td class="num"><span class="card-swatch" style="background:' + clientColor(id) + '"></span>' + esc(id) + '</td>' +
        '<td class="num">' + c.count + '</td>' +
        '<td class="num">' + fmt(c.size, 1) + '</td>' +
        '<td class="num">' + fmt(span, 3) + '</td>' +
        '<td class="num">' + fmt(c.size / span, 3) + '</td>' +
        '</tr>';
    });
    el.clientBody.innerHTML = html;
  }

  function renderWorkers() {
    var run = state.runs[state.active];
    if (!run) return;
    var busy = new Array(state.config.threads).fill(0);
    run.dispatchLog.forEach(function (d) { busy[d.workerId] += d.finish - d.start; });
    var span = Math.max(run.summary.totalCompletionTime, 1e-9);
    var html = '';
    for (var w = 0; w < state.config.threads; w++) {
      html += '<tr><td class="num">T' + w + '</td><td class="num">' + fmt(busy[w], 3) +
        '</td><td class="num">' + fmt(busy[w] / span * 100, 1) + '%</td></tr>';
    }
    el.workerBody.innerHTML = html;
  }

  /* ------------------------------------------------------------------ *
   * Diagnostics for automated checks
   * ------------------------------------------------------------------ */
  function setDiag() {
    state.runSeq += 1;
    el.body.dataset.status = 'ready';
    el.diag.textContent = JSON.stringify({
      status: 'ready',
      runSeq: state.runSeq,
      workload: state.workloadId,
      source: state.sourceLabel || '',
      requests: state.requests.length,
      threads: state.config.threads,
      quantumSec: state.config.quantumSec,
      overheadSec: state.config.overheadSec,
      schedulers: state.selected,
      dispatches: state.selected.reduce(function (acc, n) { return acc + state.runs[n].dispatches; }, 0),
      summaryRows: state.selected.length,
      detailRows: el.detailBody.children.length,
      makespan: state.makespan
    });
  }

