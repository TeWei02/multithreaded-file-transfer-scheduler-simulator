  function runAll() {
    if (!String(state.csvText || '').trim()) {
      showError('No workload selected yet. Choose one of the bundled datasets above, generate one in the browser, or upload/paste a CSV.');
      el.runStatus.textContent = '';
      return;
    }
    var parsed = MFTS.parseRequestsCsv(state.csvText);
    if (parsed.error) {
      showError('Workload could not be read: ' + parsed.error);
      el.runStatus.textContent = '';
      return;
    }
    if (parsed.requests.length === 0) {
      showError('The selected workload is empty. Upload or paste a CSV to run the simulation.');
      el.runStatus.textContent = '';
      return;
    }
    el.errorBanner.hidden = true;

    state.config = readConfig();
    state.requests = parsed.requests;
    state.runs = {};

    var t0 = (window.performance && performance.now) ? performance.now() : Date.now();
    state.selected.forEach(function (name) {
      var run = MFTS.runOneScheduler(name, parsed.requests, state.config);
      run.dispatches = run.dispatchLog.length;
      run.utilization = MFTS.workerUtilization(run, state.config);
      state.runs[name] = run;
    });
    var t1 = (window.performance && performance.now) ? performance.now() : Date.now();

    var active = state.runs[state.active] ? state.active : state.selected[0];
    setActive(active, true);

    var makespan = 0;
    var times = [];
    state.selected.forEach(function (name) {
      makespan = Math.max(makespan, state.runs[name].summary.totalCompletionTime);
    });
    state.makespan = makespan;
    state.playhead = makespan;
    el.scrub.value = '1';

    var run = state.runs[state.active];
    run.dispatchLog.forEach(function (d) { times.push(d.start); });
    times.sort(function (a, b) { return a - b; });
    state.eventTimes = times.filter(function (t, i) { return i === 0 || t - times[i - 1] > 1e-9; });

    el.runStatus.textContent = parsed.requests.length + ' requests · ' + state.selected.length +
      ' schedulers · ' + (t1 - t0).toFixed(1) + ' ms in this browser';

    render();
    setDiag();
  }

