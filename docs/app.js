  function download(filename, text, mime) {
    var blob = new Blob([text], { type: (mime || 'text/csv') + ';charset=utf-8' });
    var url = URL.createObjectURL(blob);
    var a = document.createElement('a');
    a.href = url;
    a.download = filename;
    document.body.appendChild(a);
    a.click();
    document.body.removeChild(a);
    setTimeout(function () { URL.revokeObjectURL(url); }, 4000);
  }

  /* mulberry32: small deterministic PRNG used only for the in-browser generator. */
  function mulberry32(seed) {
    var a = seed >>> 0;
    return function () {
      a = (a + 0x6D2B79F5) >>> 0;
      var t = a;
      t = Math.imul(t ^ (t >>> 15), t | 1);
      t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  /* Browser-side workload generator. Shapes of the distributions follow the
     generator documented in the README; the random sequence does not match
     the C++ std::mt19937 stream. */
  function generateCsv(n, seed) {
    var rnd = mulberry32(seed);
    var lines = ['request_id,client_id,arrival_time,file_size_mb,estimated_bandwidth_mb_per_sec,priority'];
    var arrival = 0;
    for (var i = 0; i < n; i++) {
      arrival += rnd() * 1.6;
      var clientId = 1 + Math.floor(rnd() * 12);
      var size = 10 + rnd() * 890;
      var bw = 5 + rnd() * 75;
      var prio = 1 + Math.floor(rnd() * 10);
      lines.push([i + 1, clientId, arrival.toFixed(4), size.toFixed(4), bw.toFixed(4), prio].join(','));
    }
    return lines.join('\n');
  }

