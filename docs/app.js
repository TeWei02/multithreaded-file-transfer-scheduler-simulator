  function setActive(name, silent) {
    state.active = name;
    var run = state.runs[name];
    if (run) {
      state.makespan = Math.max(state.makespan, run.summary.totalCompletionTime);
      var times = run.dispatchLog.map(function (d) { return d.start; })
        .sort(function (a, b) { return a - b; });
      state.eventTimes = times.filter(function (t, i) { return i === 0 || t - times[i - 1] > 1e-9; });
    }
    if (!silent) {
      stopPlayback();
      state.playhead = state.makespan;
      el.scrub.value = '1';
      renderTabs();
      renderGantt();
      renderDetail();
      renderClients();
      renderWorkers();
      updateClock();
    }
  }

